// Extract original data and human-readable routine descriptions; no inferred rules.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const {loadOriginal} = require('./runtime.cjs');
const {context, source} = loadOriginal();
const data = vm.runInContext(`({
 routines: Game_routineSpecs_1526730038.map((r,i)=>({id:i+1,name:toJSStr(r.name),stepCount:r.stepCount,steps:r.stepDescs.map(toJSStr),procedure:r.routineProc.name})),
 icons: romData_1409288915.icons,
 centersY:romData_1409288915.sprites.map(s=>s.centerY),
 notes: Array.from(noteToHz_1811939412),
 fonts:romData_1409288915.fontChars.map(f=>Object.keys(f).reduce((m,b)=>m|(1<<b),0)),
 textIcons:Array.from(textIconIds_1543504086),
 groups:groups_1560281484,starts:Array.from(starts_1560281483),codes:Array.from(codes_1560281482),
 theme:Array.from(kMelodyTheme_1526726916),
 segmentIds:segIds_721420499.map(toJSStr)
})`, context);
fs.writeFileSync(path.join(__dirname,'recovered/segment-ids.json'),JSON.stringify(data.segmentIds)+'\n');
const sha = crypto.createHash('sha256').update(source).digest('hex');
fs.writeFileSync(path.join(__dirname,'recovered/routines.json'), JSON.stringify({sourceSha256:sha,routines:data.routines},null,2)+'\n');
fs.writeFileSync(path.join(__dirname,'recovered/routines.md'), '# Recovered original routine descriptions\n\nVerbatim strings embedded in the Nim-generated JavaScript. These describe the scripts; they are not the complete game source.\n\n'+data.routines.map(r=>`## ${r.id}: ${r.name}\n\nProcedure: \`${r.procedure}\`\n\n`+r.steps.map((s,i)=>`${i}. \`${s}\``).join('\n')).join('\n\n')+'\n');
const indices = [], offsets = [0];
for(const icon of data.icons){indices.push(...icon.spriteIndexes); offsets.push(indices.length);}
const children=[],childOffsets=[0];
for(const icon of data.icons){children.push(...icon.childIconIds);childOffsets.push(children.length);}
const c = `/* Generated by recover.cjs from original source SHA256 ${sha}. */\n`+
`static const uint16_t icon_offsets[] = {${offsets.join(',')}};\n`+
`static const uint16_t icon_sprites[] = {${indices.join(',')}};\n`+
`static const uint16_t icon_child_offsets[] = {${childOffsets.join(',')}};\n`+
`static const uint16_t icon_children[] = {${children.join(',')}};\n`+
`static const int32_t sprite_center_y[] = {${data.centersY.join(',')}};\n`+
`static const double note_hz[] = {${data.notes.join(',')}};\n`;
fs.writeFileSync(path.join(__dirname,'native/rom_tables.inc'),c);
const table=(type,name,values)=>`static const ${type} ${name}[] = {${values.join(',')}};\n`;
fs.writeFileSync(path.join(__dirname,'native/text_tables.inc'),`/* Original data, SHA256 ${sha}. */\n`+table('uint16_t','font_masks',data.fonts)+table('uint16_t','text_icons',data.textIcons)+table('uint16_t','strand_starts',data.starts)+table('uint16_t','strand_codes',data.codes)+table('uint16_t','strand_first',data.groups.map(g=>g.firstStartIndex))+table('uint16_t','strand_counts',data.groups.map(g=>g.count))+table('uint8_t','theme_notes',data.theme));
console.log(JSON.stringify({routines:data.routines.length,steps:data.routines.reduce((n,r)=>n+r.steps.length,0),icons:data.icons.length,notes:data.notes.length}));
