// Assignment LUT only: never infer or reassign nets from touching traces.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const P=require('../2_refine_routing/project');require('../2_refine_routing/segments-data');
const file=process.argv[2];if(!file)throw Error('Usage: node 4_game_runtime/build-lcd-lut.cjs ROUTING_JSON');
const source=fs.readFileSync(file),raw=JSON.parse(source),sha=crypto.createHash('sha256').update(source).digest('hex');
const preview=JSON.parse(fs.readFileSync(path.join(__dirname,'recovered/routed-panel.json')));
assert.equal(sha,preview.sourceSha256,'Use the same snapshot as the simulator (regenerate routed panel first)');
const base=P.islandData(global.ROUTER_DATA);assert.equal(raw.sourceHash,base.sourceHash);
const data=P.layoutData(base,raw.cuts,undefined,raw.localGeometry),ids=JSON.parse(fs.readFileSync(path.join(__dirname,'recovered/segment-ids.json')));
const ports=P.getPorts(raw),resolve=(net,layer)=>{const matches=ports.filter(p=>p.layer===layer&&raw.pads[p.id]===net);assert.equal(matches.length,1,`Net ${net} must resolve to exactly one ${layer} contact`);return matches[0];};
const cells=Array(768).fill(65535),rows=[],seen=new Set();
for(const island of data.segments){
 assert.equal(ids[island.bit],island.parentId);
 const a=raw.assignments[island.id];assert(a?.top&&a?.bottom,`Unassigned ${island.id}`);
 const top=resolve(a.top,'top'),bottom=resolve(a.bottom,'bottom');
 const seg=Number(top.id.slice(-3))-1,com=Number(bottom.id.slice(-3))-1;
 assert(seg>=0&&seg<48&&com>=0&&com<16);
 const cell=com*48+seg;assert(cells[cell]===65535||cells[cell]===island.bit,`Conflicting game bits on ${top.id}/${bottom.id}`);cells[cell]=island.bit;seen.add(island.bit);
 rows.push({island:island.id,originalSegment:island.parentId,bit:island.bit,word:island.bit>>>5,mask:'0x'+(2**(island.bit&31)).toString(16).padStart(8,'0'),seg,com,topNet:a.top,bottomNet:a.bottom,topContact:top.id,bottomContact:bottom.id,topZebraSlot:seg+19,bottomZebraSlot:com+1});
}
assert.equal(seen.size,631,'Every game segment must reach a cell');assert.equal(raw.contactLayout,'zebra');
const out=path.join(__dirname,'lcd');fs.mkdirSync(out,{recursive:true});
const info={sourceSha256:sha,sourceFile:path.basename(file),indexing:'bit/word/seg/com are zero-based; zebra slots are one-based, front-view left to right; slots 17 and 18 empty',cellsUsed:cells.filter(x=>x!==65535).length,islands:rows,contacts:ports.map(p=>({id:p.id,net:raw.pads[p.id],layer:p.layer,xMm:p.x*raw.settings.widthMm/3000,yMm:p.y*raw.settings.widthMm/3000}))};
fs.writeFileSync(path.join(out,'mapping.json'),JSON.stringify(info,null,2)+'\n');
fs.writeFileSync(path.join(out,'mapping.csv'),Object.keys(rows[0]).join(',')+'\n'+rows.map(r=>Object.values(r).join(',')).join('\n')+'\n');
fs.writeFileSync(path.join(out,'moida_lcd_lut.h'),`/* Generated by build-lcd-lut.cjs. Source SHA256: ${sha}
 * Logical COM/SEG electrodes, NOT LCD-driver register or MCU pin numbers. */
#ifndef MOIDA_LCD_LUT_H
#define MOIDA_LCD_LUT_H
#include <stdint.h>
#define MOIDA_LCD_COM_COUNT 16
#define MOIDA_LCD_SEG_COUNT 48
#define MOIDA_LCD_UNUSED UINT16_C(65535)
/* COM-major: cell = com*48 + seg. Same game bit may drive multiple cells. */
static const uint16_t moida_lcd_game_bit[768] = {
${Array.from({length:16},(_,i)=>' '+cells.slice(i*48,i*48+48).join(',')).join(',\n')}
};
/* Input is MoidaFrame.display.data (20 words). Output is 16 rows of 6 bytes.
 * Within a row, byte=seg/8, bit=seg%8, least-significant bit first.
 * Clears unused cells. Caller supplies 96 bytes; input/output must not overlap.
 * This produces desired ON/OFF states, not AC drive waveforms. */
static inline void moida_lcd_map(const uint32_t words[20], uint8_t out[16][6]) {
 for(unsigned c=0;c<16;c++)for(unsigned b=0;b<6;b++)out[c][b]=0;
 for(unsigned c=0;c<16;c++)for(unsigned s=0;s<48;s++){
  unsigned bit=moida_lcd_game_bit[c*48+s];
  if(bit!=MOIDA_LCD_UNUSED && ((words[bit>>5]>>(bit&31))&1u))out[c][s>>3]|=(uint8_t)(1u<<(s&7));
 }
}
#endif
`);
console.log(`${rows.length} islands, ${seen.size} game bits, ${info.cellsUsed}/768 electrode pairs; no assignment conflicts.`);
