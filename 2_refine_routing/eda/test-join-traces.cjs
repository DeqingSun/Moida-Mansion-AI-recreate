const assert=require('node:assert/strict'),join=require('./join-traces.cjs');
const t=(id,a,b,extra={})=>({id,layer:'top',net:'T1',widthMm:.12,points:[a,b],...extra});
const chain=[t('a',[0,0],[10,0]),t('b',[10,10],[10,0]),t('c',[10,10],[20,10])];
assert.deepEqual(join(chain,150)[0].points,[[0,0],[10,0],[10,10],[20,10]]);
assert.equal(join([...chain,t('d',[10,0],[20,0])],150).length,3);
assert.equal(join([chain[0],{...chain[1],layer:'bottom'}],150).length,2);
assert.equal(join([chain[0],{...chain[1],net:'T2'}],150).length,2);
assert.equal(join([chain[0],{...chain[1],widthMm:.2}],150).length,2);
assert.equal(join([chain[0],{...chain[1],widthMm:.1199996}],150).length,1);
const loop=join([t('a',[0,0],[10,0]),t('b',[10,0],[0,10]),t('c',[0,10],[0,0])],150);
assert.equal(loop.length,1);assert.equal(loop[0].points.length,4);assert.deepEqual(loop[0].points[0],loop[0].points.at(-1));
assert.equal(join([chain[0],t('b',[10.00001,0],[10,10])],150).length,1);
assert.equal(join([chain[0],t('b',[10.01,0],[10,10])],150).length,2);
assert.equal(join([t('a',[0,0],[10,0]),t('b',[5,0],[5,10])],150).length,2,'interior contact is not an endpoint bend');
assert.equal(new Set(join([...chain,t('d',[30,0],[40,0])],150).map(t=>t.id)).size,2);
assert.equal(chain[1].points[0][0],10,'does not mutate input');
console.log('Trace chain regression tests passed');
const C=require('./convert.cjs');const r=C.importTraces(require('path').join(__dirname,'exports/Moida-LCD'));
assert(r.summary.traceWires<=r.summary.traceSegments);
assert.equal(r.project.traces.reduce((n,t)=>n+t.points.length-1,0),r.summary.traceSegments);
console.log('Saved PCB:',r.summary);
